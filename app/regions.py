# uid -> назва (статичний каталог, з офіційної alerts-in-ua-py)
STATIC_TITLES: dict[int, str] = {uid: name for uid, (name, _) in OBLASTS.items()}
STATIC_TITLES.update(CHILD_TITLES)

# uid дитини -> uid області (статично)
STATIC_PARENT: dict[int, int] = {
    child: oblast for oblast, (_, children) in OBLASTS.items() for child in children
}

STATIC_TYPES: dict[int, str] = {
    **{uid: ("city" if name.startswith("м. ") else "oblast") for uid, (name, _) in OBLASTS.items()},
    **{uid: ("city" if name.startswith("м. ") else "raion") for uid, name in CHILD_TITLES.items()},
}


def seed_rows() -> list[dict]:
    """Статичний каталог у форматі таблиці regions — для першого наповнення БД."""
    rows = [
        {"uid": uid, "title": name, "type": STATIC_TYPES.get(uid, "oblast"), "parent_uid": None}
        for uid, (name, _) in OBLASTS.items()
    ]
    rows += [
        {"uid": uid, "title": name, "type": STATIC_TYPES.get(uid, "raion"),
         "parent_uid": STATIC_PARENT.get(uid)}
        for uid, name in CHILD_TITLES.items()
    ]
    return rows


# --- доступ до каталогу: спершу БД (її наповнює провайдер), потім статика ----

_CACHE: dict[int, dict] = {}
_CACHE_AT: float = 0.0
_CACHE_TTL = 60.0  # каталог змінюється раз на добу, читати його щоразу немає сенсу


def _db_rows(force: bool = False) -> dict[int, dict]:
    global _CACHE, _CACHE_AT
    import time
    from . import db
    if not force and _CACHE and time.monotonic() - _CACHE_AT < _CACHE_TTL:
        return _CACHE
    try:
        with db.connect() as conn:
            rows = conn.execute("SELECT uid, title, type, parent_uid FROM regions").fetchall()
    except Exception:
        return _CACHE
    _CACHE = {r["uid"]: dict(r) for r in rows}
    _CACHE_AT = time.monotonic()
    return _CACHE


def title(uid) -> str:
    try:
        uid = int(uid)
    except (TypeError, ValueError):
        return f"UID {uid}"
    row = _db_rows().get(uid)
    if row:
        return row["title"]
    return STATIC_TITLES.get(uid, f"UID {uid}")


def family(uid: int) -> set[int]:
    """Регіон плюс усі його нащадки на будь-яку глибину (область -> райони -> громади)."""
    rows = _db_rows()
    if rows:
        children: dict[int, list[int]] = {}
        for r in rows.values():
            if r["parent_uid"] is not None:
                children.setdefault(r["parent_uid"], []).append(r["uid"])
        out, stack = {uid}, [uid]
        while stack:
            for child in children.get(stack.pop(), []):
                if child not in out:
                    out.add(child)
                    stack.append(child)
        return out
    if uid in OBLASTS:
        return {uid, *OBLASTS[uid][1]}
    return {uid}


def tree() -> list[dict]:
    """Дві верхні ланки для селектора: області з районами.

    Громади в список не виводимо — їх сотні, а на мобільному це нечитно;
    у підрахунок вони все одно потрапляють через family().
    """
    rows = _db_rows()
    if rows:
        by_parent: dict[int | None, list[dict]] = {}
        for r in rows.values():
            by_parent.setdefault(r["parent_uid"], []).append(r)
        out = []
        for top in by_parent.get(None, []):
            kids = sorted(by_parent.get(top["uid"], []), key=lambda r: r["title"])
            out.append({
                "uid": top["uid"], "title": top["title"],
                "children": [{"uid": k["uid"], "title": k["title"]} for k in kids],
            })
        if out:
            out.sort(key=lambda r: r["title"])
            return out
    out = [
        {"uid": uid, "title": name,
         "children": [{"uid": c, "title": CHILD_TITLES.get(c, str(c))} for c in children]}
        for uid, (name, children) in OBLASTS.items()
    ]
    out.sort(key=lambda r: r["title"])
    return out
